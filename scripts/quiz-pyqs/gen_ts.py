"""Generate src/lib/data/quiz/*.ts from the extracted JSON.

Usage: python -I gen_ts.py <out-json-dir> <repo-root>
Reads every sitting's JSON in <out-json-dir>, so keep all quiz sittings there.
"""
import glob, importlib.util, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


# Loaded by path: the End Term scripts have modules with the same names.
COURSES = load("quiz_subjects", os.path.join(HERE, "subjects.py")).COURSES
end_term = load("end_term_gen_ts", os.path.join(HERE, "..", "end-term-pyqs", "gen_ts.py"))
question, to_ts, SESSION = end_term.question, end_term.to_ts, end_term.SESSION

# Sitting key without the session -> quiz number, date and the IITM term it belongs to.
SITTINGS = {
    "quiz-2-aug-2025": {"quiz": 2, "date": "2025-08-03", "label": "3 Aug 2025", "term": "May 2025"},
    "quiz-1-oct-2025": {"quiz": 1, "date": "2025-10-26", "label": "26 Oct 2025", "term": "September 2025"},
}
DURATION_MIN = 60
LEVEL_ORDER = ["foundation", "diploma-programming", "diploma-data-science", "degree"]


def camel(prefix):
    parts = prefix.split("-")
    return parts[0] + "".join(p.capitalize() for p in parts[1:]) + "QuizPapers"


def main(out_dir, repo):
    by_course = {}
    for f in sorted(glob.glob(f"{out_dir}/*.json")):
        d = json.load(open(f))
        sit, sess = d["sitting"].rsplit("-", 1)  # quiz-1-oct-2025, an
        meta = SITTINGS[sit]
        code, word = SESSION[sess]
        for p in d["papers"]:
            prefix = p["slug"][: -len(d["sitting"]) - 1]
            subject_slug, name, short, level = COURSES[prefix]
            section = {"subjectSlug": subject_slug, "title": name, "short": short}
            if p.get("reference"):
                section["reference"] = p["reference"]
            section["questions"] = [question(p["slug"], q) for q in p["questions"]]
            paper = {
                "slug": p["slug"],
                "title": f"{short} Quiz {meta['quiz']} · {meta['label']} ({code})",
                "description": f"Quiz {meta['quiz']} paper from the {meta['term']} term, {word} session on {meta['label']}, with the official answer key.",
                "difficulty": "Standard",
                "durationMin": DURATION_MIN,
                "quiz": {"number": meta["quiz"], "date": meta["date"], "session": code, "term": meta["term"]},
                "sections": [section],
            }
            by_course.setdefault(prefix, []).append(paper)

    data_dir = f"{repo}/src/lib/data/quiz"
    os.makedirs(data_dir, exist_ok=True)
    imports, spread, subject_rows = [], [], []
    # Curriculum order: COURSES lists courses level by level.
    for prefix, (subject_slug, name, short, level) in sorted(COURSES.items(), key=lambda kv: LEVEL_ORDER.index(kv[1][3])):
        papers = by_course.get(prefix)
        if not papers:
            continue
        # Newest sitting first; forenoon before afternoon on the same day.
        papers.sort(key=lambda p: (p["quiz"]["date"], p["quiz"]["session"] == "FN"), reverse=True)
        var = camel(prefix)
        qn = sum(len(p["sections"][0]["questions"]) for p in papers)
        header = (
            'import type { QualifierMock } from "../../types";\n\n'
            f"// {name}: IIT Madras BS quiz papers ({len(papers)} {'paper' if len(papers) == 1 else 'papers'}, {qn} questions).\n"
            "// Questions, options and answer keys are reproduced from the official question papers.\n"
            "// Figures, code and maths typeset as images are in public/pyq/<slug>/, embedded inline as\n"
            "// ![Figure](src#WxH). Range answers are stored as midpoint ± tolerance.\n"
            "// Generated by scripts/quiz-pyqs from the paper PDFs; edit with care.\n\n"
        )
        with open(f"{data_dir}/{prefix}.ts", "w") as fh:
            fh.write(header + f"export const {var}: QualifierMock[] = " + to_ts(papers) + ";\n")
        imports.append(f'import {{ {var} }} from "./{prefix}";')
        spread.append(f"  ...{var},")
        subject_rows.append(f'  {{ slug: "{subject_slug}", prefix: "{prefix}", name: "{name}", short: "{short}", level: "{level}" }},')

    subjects_ts = (
        "// Courses with quiz papers. Kept apart from the question data so URL helpers\n"
        "// (lib/pyq-urls.ts) can use it without loading the papers.\n\n"
        'import type { EndTermSubject } from "../end-term/subjects";\n\n'
        "/** `prefix` starts every paper slug of the course, e.g. stats-1-quiz-1-oct-2025-an. */\n"
        "export type QuizSubject = EndTermSubject;\n\n"
        "/** Courses with quiz papers, in curriculum order. */\n"
        "export const QUIZ_SUBJECTS: QuizSubject[] = [\n" + "\n".join(subject_rows) + "\n];\n"
    )
    with open(f"{data_dir}/subjects.ts", "w") as fh:
        fh.write(subjects_ts)
    index = (
        'import type { QualifierMock } from "../../types";\n'
        + "\n".join(imports)
        + "\n\n"
        "// IIT Madras BS Quiz 1 and Quiz 2 previous-year papers, one single-course paper per subject per sitting.\n"
        "// Server-only: the site reads papers from Supabase (lib/papers.ts); scripts/seed-papers.mts uploads these.\n\n"
        'export { QUIZ_SUBJECTS, type QuizSubject } from "./subjects";\n\n'
        "export const quizPapers: QualifierMock[] = [\n" + "\n".join(spread) + "\n];\n"
    )
    with open(f"{data_dir}/index.ts", "w") as fh:
        fh.write(index)
    print("courses", len(subject_rows), "papers", sum(len(v) for v in by_course.values()))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
